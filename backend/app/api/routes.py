log = logging.getLogger(__name__)
router = APIRouter(prefix="/api")


_CLIENT_ID = re.compile(r"^[A-Za-z0-9_-]{16,64}$")


def _client_id(request: Request) -> str | None:
    """Anonymous per-browser id (random, generated by the frontend). It scopes the HISTORY LIST so visitors can't
    browse each other's research. It is not authentication: a report is reachable by anyone who has its (unguessable)
    link, which is what makes sharing a report URL possible."""
    v = request.headers.get("x-client-id", "")
    return v if _CLIENT_ID.match(v) else None


def _row_or_404(rid: str) -> dict:
    row = db.get_research(rid)
    if not row:
        raise ResearchError("NOT_FOUND", "Research not found.", status_code=404)
    return row


def _dt(v: str | None) -> datetime | None:
    return datetime.fromisoformat(v) if v else None


def _require_keys() -> None:
    s = get_settings()
    missing = [n for n, ok in (("TAVILY_API_KEY", s.tavily_configured), ("GEMINI_API_KEY", s.gemini_configured)) if not ok]
    if missing:
        raise ResearchError(
            "NOT_CONFIGURED",
            f"Missing server configuration: {', '.join(missing)}. Add it to the .env file and restart the backend.",
            status_code=503,
        )


def _status_model(row: dict) -> ResearchStatus:
    sources = [Source(**{k: v for k, v in s.items() if k != "evidence_text"}) for s in json.loads(row["sources_json"])]
    return ResearchStatus(
        id=row["id"], topic=row["topic"], mode=row["mode"], status=row["status"], stage=row["stage"],
        progress=row["progress"], saved=bool(row["saved"]), created_at=_dt(row["created_at"]),
        completed_at=_dt(row["completed_at"]),
        error=json.loads(row["error_json"]) if row["error_json"] else None,
        warnings=json.loads(row["warnings_json"]), objective=row["objective"],
        queries=json.loads(row["queries_json"]), sources=sources,
        report=Report(**json.loads(row["report_json"])) if row["report_json"] else None,
        follow_ups=[FollowUpAnswer(**a) for a in db.list_followups(row["id"])],
    )


def _completed_report(row: dict) -> Report:
    if row["status"] != "completed" or not row["report_json"]:
        raise ResearchError(
            "NOT_READY",
            "The report is not ready yet." if row["status"] in ("queued", "running")
            else "This research did not complete, so there is no report. Retry it from the history.",
            status_code=409,
        )
    return Report(**json.loads(row["report_json"]))


@router.get("/health", response_model=HealthStatus)
async def health() -> HealthStatus:
    s = get_settings()
    ok = s.tavily_configured and s.gemini_configured
    return HealthStatus(
        status="ok" if ok else "degraded", tavily_configured=s.tavily_configured,
        gemini_configured=s.gemini_configured, gemini_model=s.gemini_model,
    )


@router.post("/research", response_model=ResearchCreated, status_code=202, dependencies=[Depends(rate_limit)])
async def start_research(req: ResearchRequest, background: BackgroundTasks, request: Request) -> ResearchCreated:
    _require_keys()
    cid = _client_id(request)
    if not cid:
        raise ResearchError(
            "CLIENT_ID_REQUIRED", "Missing or invalid X-Client-Id header (16-64 letters, digits, - or _).", status_code=400
        )
    rid = db.create_research(req.topic, req.mode, cid)
    background.add_task(run_research, rid)
    log.info("[%s] accepted mode=%s", rid, req.mode)
    return ResearchCreated(research_id=rid, status="queued")


@router.get("/research/{research_id}", response_model=ResearchStatus)
async def get_research(research_id: str) -> ResearchStatus:
    return _status_model(_row_or_404(research_id))


@router.get("/research/{research_id}/report", response_model=Report)
async def get_report(research_id: str) -> Report:
    return _completed_report(_row_or_404(research_id))


@router.get("/research/{research_id}/pdf")
async def get_pdf(research_id: str) -> Response:
    row = _row_or_404(research_id)
    report = _completed_report(row)
    data = await asyncio.to_thread(pdf_service.build_pdf, report, row["topic"])
    slug = re.sub(r"[^a-z0-9]+", "-", report.title.lower()).strip("-")[:60] or "report"
    return Response(
        content=data, media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="webwise-{slug}.pdf"'},
    )


@router.post("/research/{research_id}/follow-up", response_model=FollowUpAnswer, dependencies=[Depends(rate_limit)])
async def follow_up(research_id: str, req: FollowUpRequest) -> FollowUpAnswer:
    row = _row_or_404(research_id)
    report = _completed_report(row)
    sources = [EvidenceSource(**s) for s in json.loads(row["sources_json"])]
    history = [FollowUpAnswer(**a) for a in db.list_followups(research_id)]
    answer = await followup_service.answer_followup(req.question, report, sources, history)
    db.add_followup(research_id, answer.model_dump(mode="json"))
    return answer


@router.post("/research/{research_id}/retry", response_model=ResearchCreated, status_code=202, dependencies=[Depends(rate_limit)])
async def retry_research(research_id: str, background: BackgroundTasks) -> ResearchCreated:
    row = _row_or_404(research_id)
    if row["status"] in ("queued", "running"):
        raise ResearchError("ALREADY_RUNNING", "This research is still running.", status_code=409)
    _require_keys()
    db.reset_for_retry(research_id)
    background.add_task(run_research, research_id)
    return ResearchCreated(research_id=research_id, status="queued")


@router.patch("/research/{research_id}/saved", response_model=ResearchStatus)
async def set_saved(research_id: str, req: SavedRequest) -> ResearchStatus:
    _row_or_404(research_id)
    db.set_saved(research_id, req.saved)
    return _status_model(_row_or_404(research_id))


@router.delete("/research/{research_id}", status_code=204)
async def delete_research(research_id: str) -> Response:
    _row_or_404(research_id)
    db.delete_research(research_id)
    return Response(status_code=204)


@router.get("/history", response_model=list[HistoryItem])
async def history(
    request: Request,
    saved: bool = False,
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
) -> list[HistoryItem]:
    return [
        HistoryItem(
            id=r["id"], topic=r["topic"], mode=r["mode"], status=r["status"], title=r["title"],
            sources_count=r["sources_count"], saved=bool(r["saved"]),
            created_at=_dt(r["created_at"]), completed_at=_dt(r["completed_at"]),
        )
        for r in db.list_history(limit, offset, saved, _client_id(request))
    ]
